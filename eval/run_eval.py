"""Run the agent on every case in eval/questions.json and grade the answers automatically.

    python -m eval.run_eval                      # all cases; writes eval/results.md and eval/results.json
    python -m eval.run_eval --only refund-cw1002 # some cases; prints only, does not overwrite results
    python -m eval.run_eval --regrade            # re-grade the saved answers after changing the graders (no API calls)
"""

import argparse
import json
import time
from collections import Counter
from dataclasses import asdict
from datetime import datetime, timezone
from pathlib import Path

import anthropic
from dotenv import load_dotenv

from citywheels.agent import Agent
from citywheels.llm import ClaudeModel, describe_api_error
from eval.checks import grade

EVAL_DIR = Path(__file__).resolve().parent
# USD per million tokens, for the cost estimate in the report.
PRICES = {"claude-opus-5-5": {"input": 4.0, "output": 20.0, "cache_read": 0.20, "cache_write": 5.0}}


class UsageMeter:
    """Wraps the model and adds up token usage over all requests."""

    def __init__(self, model):
        self.model = model
        self.requests = 0
        self.tokens = Counter()

    def create(self, **kwargs):
        response = self.model.create(**kwargs)
        self.requests += 1
        usage = response.usage
        self.tokens["input"] += usage.input_tokens or 0
        self.tokens["output"] += usage.output_tokens or 0
        self.tokens["cache_read"] += getattr(usage, "cache_read_input_tokens", 0) or 0
        self.tokens["cache_write"] += getattr(usage, "cache_creation_input_tokens", 0) or 0
        return response

    def cost_usd(self, model_name: str) -> float | None:
        prices = PRICES.get(model_name)
        if prices is None:
            return None
        return sum(self.tokens[k] * prices[k] for k in prices) / 1_000_000


def run_case(case: dict, model) -> dict:
    agent = Agent(model)
    started = time.monotonic()
    record = {"id": case["id"], "category": case["category"], "turns": case["turns"], "answers": []}
    all_tool_calls = []
    try:
        for turn in case["turns"]:
            result = agent.ask(turn)
            record["answers"].append(result.answer)
            all_tool_calls += [asdict(c) for c in result.tool_calls]
    except anthropic.AnthropicError as exc:
        record.update(error=describe_api_error(exc), tool_calls=[], all_tool_calls=all_tool_calls)
    else:
        record.update(error=None, tool_calls=[asdict(c) for c in result.tool_calls], all_tool_calls=all_tool_calls)
    record["seconds"] = round(time.monotonic() - started, 1)
    return apply_grades(record, case)


def apply_grades(record: dict, case: dict) -> dict:
    if record["error"]:
        record.update(passed=False, checks=[])
    else:
        all_tool_calls = record.setdefault("all_tool_calls", record["tool_calls"])  # older results lack it
        checks = grade(case["expect"], record["answers"][-1], record["tool_calls"], all_tool_calls)
        record.update(passed=all(c["passed"] for c in checks), checks=checks)
    return record


def _quote(text: str) -> str:
    return "\n".join(f"> {line}" if line else ">" for line in text.splitlines())


def write_markdown(path: Path, records: list[dict], meta: dict) -> None:
    passed = sum(r["passed"] for r in records)
    lines = [
        "# Evaluation results",
        "",
        f"**Passed: {passed} / {len(records)}**",
        "",
        f"- Run at: {meta['run_at']} (the agent's own \"now\" is fixed at 2026-06-10 09:00 +02:00)",
        f"- Model: `{meta['model']}`, effort `{meta['effort']}`",
        f"- API requests: {meta['requests']}, tokens: {meta['tokens']}",
        f"- Estimated cost: {meta['cost']}",
        f"- Total time: {meta['seconds']} s",
        *[f"- Note: {note}" for note in meta.get("notes", [])],
        "",
        "Generated by `python -m eval.run_eval`. Cases are in `eval/questions.json`, graders in `eval/checks.py`.",
        "",
        "| # | Case | Category | Result | Failed checks |",
        "| --- | --- | --- | --- | --- |",
    ]
    for i, r in enumerate(records, 1):
        failed = r["error"] or "; ".join(c["name"] for c in r["checks"] if not c["passed"])
        lines.append(f"| {i} | [{r['id']}](#{r['id']}) | {r['category']} | {'PASS' if r['passed'] else '**FAIL**'} | {failed} |")

    lines += ["", "## Details", ""]
    for r in records:
        lines += [f"### {r['id']}", "", f"**{'PASS' if r['passed'] else 'FAIL'}** in {r['seconds']} s", ""]
        for i, turn in enumerate(r["turns"]):
            lines += [f"**Customer:** {turn}", ""]
            if i < len(r["answers"]):
                lines += ["**Agent:**", "", _quote(r["answers"][i]), ""]
        if r["error"]:
            lines += [f"Error: {r['error']}", ""]
        if r["tool_calls"]:
            lines += ["Tool calls (last turn):", ""]
            lines += [f"- `{c['name']}({json.dumps(c['input'])})`" for c in r["tool_calls"]]
            lines.append("")
        lines += ["Checks:", ""]
        for c in r["checks"]:
            detail = f" ({c['detail']})" if c["detail"] and not c["passed"] else ""
            lines.append(f"- {'ok' if c['passed'] else 'FAILED'}: {c['name']}{detail}")
        lines.append("")
    path.write_text("\n".join(lines), encoding="utf-8")


def regrade(cases: list[dict]) -> None:
    saved = json.loads((EVAL_DIR / "results.json").read_text(encoding="utf-8"))
    by_id = {c["id"]: c for c in cases}
    before = sum(r["passed"] for r in saved["results"])
    records = [apply_grades(r, by_id[r["id"]]) for r in saved["results"] if r["id"] in by_id]
    after = sum(r["passed"] for r in records)
    print(f"Re-graded: passed {after} / {len(records)} (was {before})")
    meta = dict(saved["meta"])
    meta.setdefault("notes", []).append(
        f"Re-graded on {datetime.now(timezone.utc):%Y-%m-%d %H:%M UTC} after a grader change, same answers: "
        f"{before} -> {after} passed."
    )
    for r in records:
        if not r["passed"]:
            print(f"  FAIL {r['id']}: " + (r["error"] or "; ".join(c["name"] for c in r["checks"] if not c["passed"])))
    (EVAL_DIR / "results.json").write_text(json.dumps({"meta": meta, "results": records}, indent=2), encoding="utf-8")
    write_markdown(EVAL_DIR / "results.md", records, meta)


def main() -> None:
    parser = argparse.ArgumentParser(prog="python -m eval.run_eval", description=__doc__.splitlines()[0])
    parser.add_argument("--only", nargs="+", metavar="ID", help="run only these case ids (results files are not written)")
    parser.add_argument("--regrade", action="store_true", help="re-grade eval/results.json without calling the model")
    args = parser.parse_args()

    load_dotenv()
    cases = json.loads((EVAL_DIR / "questions.json").read_text(encoding="utf-8"))
    if args.regrade:
        regrade(cases)
        return
    if args.only:
        cases = [c for c in cases if c["id"] in args.only]

    claude = ClaudeModel()
    meter = UsageMeter(claude)
    started = time.monotonic()
    records = []
    for i, case in enumerate(cases, 1):
        record = run_case(case, meter)
        records.append(record)
        failed = record["error"] or ", ".join(c["name"] for c in record["checks"] if not c["passed"])
        print(f"[{i}/{len(cases)}] {'PASS' if record['passed'] else 'FAIL'} {case['id']} ({record['seconds']} s) {failed}")

    cost = meter.cost_usd(claude.model)
    meta = {
        "run_at": datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC"),
        "model": claude.model,
        "effort": claude.effort,
        "requests": meter.requests,
        "tokens": dict(meter.tokens),
        "cost": f"${cost:.2f} (list prices)" if cost is not None else "unknown for this model",
        "seconds": round(time.monotonic() - started, 1),
    }
    passed = sum(r["passed"] for r in records)
    print(f"\nPassed {passed} / {len(records)}. {meta['requests']} requests, cost {meta['cost']}, {meta['seconds']} s.")

    if not args.only:
        (EVAL_DIR / "results.json").write_text(json.dumps({"meta": meta, "results": records}, indent=2), encoding="utf-8")
        write_markdown(EVAL_DIR / "results.md", records, meta)
        print("Wrote eval/results.md and eval/results.json")


if __name__ == "__main__":
    main()
